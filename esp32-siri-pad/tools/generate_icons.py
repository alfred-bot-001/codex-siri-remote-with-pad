"""Rasterize the three local design SVGs into 28px LVGL RGB565 icons.

Run from the repository root with Pillow and CairoSVG installed. The icons are
blended over the actual card background so their edges render cleanly on ESP32.
"""
from io import BytesIO
from pathlib import Path
import struct

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ICONS = [
    ("openai", (15, 159, 123)),
    ("claude", (200, 109, 71)),
    ("googlechrome", (71, 119, 199)),
]
BG = (248, 247, 243)
SIZE = 28


def icon_data(name, ink):
    svg = ROOT / "design/icons" / (name + ".svg")
    raster = Image.open(BytesIO(cairosvg.svg2png(url=str(svg), output_width=112,
                                                 output_height=112))).convert("RGBA")
    alpha = raster.getchannel("A").resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    colored = Image.new("RGB", (SIZE, SIZE), ink)
    background = Image.new("RGB", (SIZE, SIZE), BG)
    image = Image.composite(colored, background, alpha)
    result = bytearray()
    for r, g, b in image.getdata():
        rgb565 = (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
        # CONFIG_LV_COLOR_16_SWAP stores RGB565 high byte first on this board.
        result += struct.pack(">H", rgb565)
    return result


lines = ["/* Generated by tools/generate_icons.py from the local design SVG icons. */",
         '#include "app_icons.h"', ""]
for name, ink in ICONS:
    data = icon_data(name, ink)
    hexlines = [", ".join(f"0x{value:02x}" for value in data[i:i + 20])
                for i in range(0, len(data), 20)]
    lines += [f"static const uint8_t {name}_pixels[] = {{",
              "    " + ",\n    ".join(hexlines), "};",
              f"const lv_img_dsc_t icon_{name} = {{",
              "    .header = { .always_zero = 0, .w = 28, .h = 28, .cf = LV_IMG_CF_TRUE_COLOR },",
              f"    .data_size = sizeof({name}_pixels), .data = {name}_pixels,",
              "};", ""]
(ROOT / "main/app_icons.c").write_text("\n".join(lines))
